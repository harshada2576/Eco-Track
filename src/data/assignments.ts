export function resolveDocUrl(url: string): string {
  const cleanUrl = url.startsWith('/') ? url.slice(1) : url;
  const base = import.meta.env.BASE_URL || './';
  return base.endsWith('/') ? `${base}${cleanUrl}` : `${base}/${cleanUrl}`;
}

